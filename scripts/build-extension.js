const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'DoorDashEnhanced.user.js');
const manifestPath = path.join(root, 'extension', 'manifest.json');
const contentPath = path.join(root, 'extension', 'content.js');
const checkOnly = process.argv.includes('--check');

const source = fs.readFileSync(sourcePath, 'utf8');
const versionMatch = source.match(/^\/\/ @version\s+([^\s]+)/m);
if (!versionMatch) throw new Error('userscript @version is missing');
const version = versionMatch[1];

const metadataEnd = source.indexOf('// ==/UserScript==');
if (metadataEnd === -1) throw new Error('userscript metadata block is missing');
const userscriptBody = source.slice(metadataEnd + '// ==/UserScript=='.length).trim();
const shim = `(function() {
    'use strict';
    var PREFIX = 'dd-enhanced-extension:';
    window.GM_getValue = function(key, fallback) {
        var raw = window.localStorage.getItem(PREFIX + key);
        if (raw === null) return fallback;
        try { return JSON.parse(raw); } catch(e) { return raw; }
    };
    window.GM_setValue = function(key, value) {
        window.localStorage.setItem(PREFIX + key, JSON.stringify(value));
    };
    window.GM_addStyle = function(css) {
        var style = document.createElement('style');
        style.textContent = css;
        (document.head || document.documentElement).appendChild(style);
        return style;
    };
    window.GM_registerMenuCommand = function() {};
})();`;
const expectedContent = '// Generated by scripts/build-extension.js. Do not edit directly.\n' + shim + '\n\n' + userscriptBody + '\n';

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (manifest.version !== version) {
    if (checkOnly) throw new Error(`extension manifest version ${manifest.version} does not match ${version}`);
    manifest.version = version;
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
}

if (checkOnly) {
    if (!fs.existsSync(contentPath)) throw new Error('extension/content.js is missing; run node scripts/build-extension.js');
    if (fs.readFileSync(contentPath, 'utf8') !== expectedContent) throw new Error('extension/content.js is out of date; run node scripts/build-extension.js');
    console.log(`extension build is current (${version})`);
} else {
    fs.writeFileSync(contentPath, expectedContent);
    console.log(`built extension/content.js (${version})`);
}
